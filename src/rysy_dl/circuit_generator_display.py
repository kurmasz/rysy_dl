default_fig = plt.figure()

def display_raw_graph(graph, graph_contains_gate_labels = False, fig=default_fig, ax=None):
    """Display a networkx graph using matplotlib.
       (That graph will usually be the DAG underlying a circuit, but it could be any networkx graph.) 
       
       param: graph: a networkx graph to display
       param: graph_contains_gate_labels: if True, the graph's nodes are labeled with gate names (otherwise the raw node lables/numbers are used)
       param: fig: a matplotlib figure to use for the display
       param: ax: a matplotlib axes to use for the display (if None, a new axes is created and placed in 1st subplot of the figure)
    """
    ax = ax or fig.add_subplot(1, 2, 1)  # 1 row, 2 columns, 1st subplot

    # Shows graphical representation
    pos = nx.spring_layout(graph)
    if graph_contains_gate_labels:
        # Labels nodes with gate names instead of nums
        labels = {node: graph.nodes[node]['gate'] for node in graph.nodes()}
        nx.draw(graph, pos, ax=ax, labels=labels, node_color='lightblue', node_size=500, font_size=10, arrows=True)
    else:
        # Labels nodes with numbers
        nx.draw(graph, pos, ax=ax, with_labels=True, node_color='lightblue', node_size=500, font_size=10, arrows=True)
    plt.show(block=False)


def display_circuit_from_bytestring(png_bytes, filename=None, fig=default_fig, ax=None,
                                     graph_width_in=4.0, circuit_width_in=5.0):
    """Display a circuit PNG using matplotlib imshow, then wait for a keypress to advance.
    Returns True if the user wants to quit.

    Circuit diagrams are laid out wide-and-short (many layers, few parallel gates),
    while display_raw_graph's spring layout is roughly square. imshow locks to the
    image's true pixel aspect ratio (unlike nx.draw, which stretches to fill its
    axes), so dropping a wide/short image into a plain square subplot leaves most
    of the box empty. To avoid that, the whole figure is resized here -- based on
    the circuit image's actual aspect ratio, known as soon as it's loaded -- so
    the circuit panel fills edge-to-edge with no distortion. This assumes
    display_raw_graph (using its own default axes) was already called on `fig`,
    so its axes can be found at fig.axes[0] and repositioned to match.

    param: graph_width_in: width (inches) reserved for the raw-graph panel (fig.axes[0])
    param: circuit_width_in: width (inches) reserved for the circuit panel
    """

    img = plt.imread(io.BytesIO(png_bytes), format="png")

    if ax is None:
        img_h, img_w = img.shape[:2]  # array shape is (rows, cols, ...) = (height, width, ...)
        aspect = img_h / img_w  # height/width of the circuit image

        left_margin, mid_gap, right_margin = 0.4, 0.5, 0.3
        top_margin, bottom_margin = 0.4, 0.6  # bottom_margin leaves room for the "Next" button

        panel_h = circuit_width_in * aspect
        fig_w = left_margin + graph_width_in + mid_gap + circuit_width_in + right_margin
        fig_h = top_margin + panel_h + bottom_margin
        fig.set_size_inches(fig_w, fig_h)

        # Reposition the raw-graph axes (added by display_raw_graph) to fill the left panel.
        # nx.draw uses aspect='auto', so it stretches cleanly to whatever box it's given.
        if fig.axes:
            fig.axes[0].set_position((left_margin / fig_w, bottom_margin / fig_h,
                                       graph_width_in / fig_w, panel_h / fig_h))

        x0 = (left_margin + graph_width_in + mid_gap) / fig_w
        ax = fig.add_axes((x0, bottom_margin / fig_h, circuit_width_in / fig_w, panel_h / fig_h))

    ax.imshow(img)
    ax.axis('off')
    
    if filename:
        ax.text(0.5, -0.06, filename, transform=ax.transAxes, ha='center', va='top')
    
    plt.show(block=False)

def display_circuit(drawing, filename=None, fig=default_fig, ax=None,
                                     graph_width_in=4.0, circuit_width_in=5.0):
     
    import cairosvg  # imported lazily: only this many-graphs debug loop needs the matplotlib-leak workaround.
    png = io.BytesIO()
    cairosvg.svg2png(bytestring=drawing.get_imagedata(fmt='svg'), write_to=png)
    display_circuit_from_bytestring(png.getvalue(), filename=filename, fig=fig, ax=ax,
                                     graph_width_in=graph_width_in, circuit_width_in=circuit_width_in)     



def set_figure_title(title, fig=default_fig):
    """Set (or replace) the figure's overall title.

    Note: wait_for_keypress calls fig.clf() when advancing to the next
    circuit, which removes this title along with everything else. So this
    must be called again for each new circuit if a title is desired throughout.

    param: title: the title text to display
    param: fig: a matplotlib figure to use for the display
    """
    fig.suptitle(title)

def wait_for_keypress(fig=default_fig):
    """Wait for the user to advance to the next circuit or quit.

    Advances (returns False) when the user either presses a key in the
    terminal (any key other than 'q' or Ctrl-C) or clicks the "Next" button
    on the figure. Exits (returns True) if the user presses 'q'/Ctrl-C in
    the terminal or closes the figure window.

    On advance, `fig` is cleared (not closed) so the same window can be
    reused to display the next circuit. It is only closed when the user
    is done (`do_exit` is True).
    """

    # These are lists so they can be modified in the nested functions below.
    do_exit = [False]
    advance = [False]

    def on_next_clicked(event):
        advance[0] = True

    def on_window_closed(event):
        do_exit[0] = True
        advance[0] = True

    # "Next" button, drawn bottom-center of the figure.
    next_button_ax = fig.add_axes((0.44, 0.01, 0.12, 0.05))
    next_button = Button(next_button_ax, 'Next')
    next_button.on_clicked(on_next_clicked)

    close_cid = fig.canvas.mpl_connect('close_event', on_window_closed)

    # Put the terminal into raw, non-blocking-read mode (if it is actually a
    # terminal) so we can poll for a single keypress without a background
    # thread -- a thread reading `sys.stdin.read(1)` can't be woken up by a
    # button click or window close, and would otherwise leak forever waiting
    # for a keystroke that may never come.
    stdin_is_tty = sys.stdin.isatty()
    old_term = None
    if stdin_is_tty:
        fd = sys.stdin.fileno()
        old_term = termios.tcgetattr(fd)
        new_term = list(old_term)
        new_term[3] &= ~(termios.ICANON | termios.ISIG | termios.ECHO)
        new_term[6][termios.VMIN] = 0
        new_term[6][termios.VTIME] = 0
        termios.tcsetattr(fd, termios.TCSAFLUSH, new_term)

    try:
        while plt.get_fignums() and not advance[0]:
            fig.canvas.draw_idle()
            fig.canvas.start_event_loop(0.05)

            if stdin_is_tty and select.select([sys.stdin], [], [], 0)[0]:
                ch = sys.stdin.read(1)
                if ch == 'q' or ch == '\x03':
                    print("Exiting ...", end='\r\n')
                    do_exit[0] = True
                advance[0] = True
    finally:
        if stdin_is_tty:
            termios.tcsetattr(fd, termios.TCSADRAIN, old_term)

    try:
        fig.canvas.mpl_disconnect(close_cid)
    except Exception:
        pass

    if do_exit[0]:
        plt.close(fig)
    else:
        # Clear the figure (rather than closing it) so it stays registered
        # with pyplot and the same window can be reused for the next circuit.
        fig.clf()

    return do_exit[0]


def show_netlist(netlist, raw_digraph, fig=default_fig):
    """Prepare and interactively display one generated circuit, for debugging.

    Labels the netlist's sources, lays it out as a circuit diagram, and shows
    that diagram side-by-side with the raw DAG it came from, then waits for
    the user to advance to the next circuit or quit.

    :param netlist: the netlist (a networkx DiGraph with 'gate' attributes assigned)
                    to lay out and display.
    :param raw_digraph: the underlying raw DAG (before gate assignment) to display
                        alongside the circuit diagram.
    :param fig: a matplotlib figure to use for the display.
    :returns: True if the user wants to quit (see `wait_for_keypress`).
    """
    circuit_layout.assign_source_labels(netlist)

    display_raw_graph(raw_digraph, fig=fig)
    set_figure_title(circuit_analyzer.circuit_to_expression(netlist), fig=fig)

    circuit_diagram = circuit_layout.layout_circuit(netlist)
    display_circuit(circuit_diagram, fig=fig)

    # wait_for_keypress returns True if the user wants to quit, False if they want to advance to the next circuit.
    return wait_for_keypress(fig=fig)
