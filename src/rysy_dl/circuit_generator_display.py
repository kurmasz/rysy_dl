"""
circuit_generator_display.py

Code to interactively display circuits, one at a time: as they are generated by circuit_generator,
or as they are read back from a circuit database (`rysy_dl view-circuits`).

This code is separated by circuit_generator.py to avoid heavy dependencies on matplotlib, schemdraw, and cairosvg in the main circuit generation code.

: copyright: Copyright (c) 2026 Zachary Kurmas
"""
import io
import select
import sys
import termios
import matplotlib.pyplot as plt
from matplotlib.widgets import Button

import schemdraw
schemdraw.use('svg')  # Use pure-Python SVG backend to avoid matplotlib's memory leak

from . import circuit_analyzer
from . import circuit_generator
from . import circuit_layout

default_fig = plt.figure()

def display_circuit_from_bytestring(png_bytes, filename=None, fig=default_fig, ax=None,
                                     circuit_width_in=5.0):
    """Display a circuit PNG using matplotlib imshow.

    Circuit diagrams are laid out wide-and-short (many layers, few parallel gates).
    imshow locks to the image's true pixel aspect ratio, so dropping a wide/short
    image into a plain square figure leaves most of it empty. To avoid that, when
    `ax` is None the whole figure is resized here -- based on the circuit image's
    actual aspect ratio, known as soon as it's loaded -- so the circuit fills the
    figure edge-to-edge with no distortion.

    param: png_bytes: the circuit diagram, as PNG data
    param: filename: if given, shown as a caption below the circuit
    param: fig: a matplotlib figure to use for the display
    param: ax: a matplotlib axes to draw into (if None, the figure is resized and a new axes is added to fill it)
    param: circuit_width_in: width (inches) of the circuit panel, used only when `ax` is None
    """

    img = plt.imread(io.BytesIO(png_bytes), format="png")

    if ax is None:
        img_h, img_w = img.shape[:2]  # array shape is (rows, cols, ...) = (height, width, ...)
        aspect = img_h / img_w  # height/width of the circuit image

        left_margin, right_margin = 0.4, 0.3
        top_margin, bottom_margin = 0.4, 0.6  # bottom_margin leaves room for the "Next" button

        panel_h = circuit_width_in * aspect
        fig_w = left_margin + circuit_width_in + right_margin
        fig_h = top_margin + panel_h + bottom_margin
        fig.set_size_inches(fig_w, fig_h)

        ax = fig.add_axes((left_margin / fig_w, bottom_margin / fig_h, circuit_width_in / fig_w, panel_h / fig_h))

    ax.imshow(img)
    ax.axis('off')
    
    if filename:
        ax.text(0.5, -0.06, filename, transform=ax.transAxes, ha='center', va='top')
    
    plt.show(block=False)

def display_circuit(drawing, filename=None, fig=default_fig, ax=None, circuit_width_in=5.0):
    """Display a schemdraw circuit diagram (e.g. from `circuit_layout.layout_circuit`).

    The diagram is rendered to PNG via SVG (see `display_circuit_from_bytestring` for the parameters).
    """
    import cairosvg  # imported lazily: only this many-graphs debug loop needs the matplotlib-leak workaround.
    png = io.BytesIO()
    cairosvg.svg2png(bytestring=drawing.get_imagedata(fmt='svg'), write_to=png)
    display_circuit_from_bytestring(png.getvalue(), filename=filename, fig=fig, ax=ax,
                                     circuit_width_in=circuit_width_in)


def set_figure_title(title, fig=default_fig):
    """Set (or replace) the figure's overall title.

    Note: wait_for_user_action calls fig.clf() when the user moves on (or asks
    for the gates to be reassigned), which removes this title along with
    everything else. So this must be called again each time a circuit is
    drawn if a title is desired throughout.

    param: title: the title text to display
    param: fig: a matplotlib figure to use for the display
    """
    fig.suptitle(title)


# What the user chose in wait_for_user_action.
NEXT = 'next'
QUIT = 'quit'
REASSIGN_GATES = 'reassign_gates'


def wait_for_user_action(fig=default_fig, show_reassign_button=False):
    """Wait for the user to advance to the next circuit, reassign its gates, or quit.

    Returns NEXT when the user either presses a key in the terminal (any key
    other than 'q', 'r', or Ctrl-C) or clicks the "Next" button on the figure.
    Returns REASSIGN_GATES when the user clicks the "Reassign Gates" button or
    presses 'r' in the terminal (only if `show_reassign_button` is True;
    otherwise 'r' is treated like any other key). Returns QUIT if the user
    presses 'q'/Ctrl-C in the terminal or closes the figure window.

    Unless the user quits, `fig` is cleared (not closed) so the same window can
    be reused to display the next (or re-gated) circuit. It is only closed when
    the user is done.

    param: fig: a matplotlib figure to use for the display
    param: show_reassign_button: if True, also show a "Reassign Gates" button next to "Next"
    """

    # A list so it can be modified in the nested functions below.
    action = [None]

    def on_next_clicked(event):
        action[0] = NEXT

    def on_reassign_clicked(event):
        action[0] = REASSIGN_GATES

    def on_window_closed(event):
        action[0] = QUIT

    # Buttons, drawn bottom-center of the figure. (The Button objects must stay referenced
    # until the loop below ends, or matplotlib stops delivering their clicks.)
    buttons = []
    if show_reassign_button:
        next_button_ax = fig.add_axes((0.32, 0.01, 0.12, 0.05))
        reassign_button_ax = fig.add_axes((0.46, 0.01, 0.22, 0.05))
        reassign_button = Button(reassign_button_ax, 'Reassign Gates')
        reassign_button.on_clicked(on_reassign_clicked)
        buttons.append(reassign_button)
    else:
        next_button_ax = fig.add_axes((0.44, 0.01, 0.12, 0.05))
    next_button = Button(next_button_ax, 'Next')
    next_button.on_clicked(on_next_clicked)
    buttons.append(next_button)

    close_cid = fig.canvas.mpl_connect('close_event', on_window_closed)

    # Put the terminal into raw, non-blocking-read mode (if it is actually a
    # terminal) so we can poll for a single keypress without a background
    # thread -- a thread reading `sys.stdin.read(1)` can't be woken up by a
    # button click or window close, and would otherwise leak forever waiting
    # for a keystroke that may never come.
    stdin_is_tty = sys.stdin.isatty()
    old_term = None
    if stdin_is_tty:
        fd = sys.stdin.fileno()
        old_term = termios.tcgetattr(fd)
        new_term = list(old_term)
        new_term[3] &= ~(termios.ICANON | termios.ISIG | termios.ECHO)
        new_term[6][termios.VMIN] = 0
        new_term[6][termios.VTIME] = 0
        termios.tcsetattr(fd, termios.TCSAFLUSH, new_term)

    try:
        while action[0] is None:
            if not plt.get_fignums():
                action[0] = QUIT
                break
            fig.canvas.draw_idle()
            fig.canvas.start_event_loop(0.05)

            if stdin_is_tty and select.select([sys.stdin], [], [], 0)[0]:
                ch = sys.stdin.read(1)
                if ch == 'q' or ch == '\x03':
                    print("Exiting ...", end='\r\n')
                    action[0] = QUIT
                elif ch == 'r' and show_reassign_button:
                    action[0] = REASSIGN_GATES
                else:
                    action[0] = NEXT
    finally:
        if stdin_is_tty:
            termios.tcsetattr(fd, termios.TCSADRAIN, old_term)

    try:
        fig.canvas.mpl_disconnect(close_cid)
    except Exception:
        pass

    # fig.clf() below removes the buttons' axes but not their canvas event handlers. A Button
    # object that is still alive afterward (e.g. not yet garbage-collected) would keep reacting
    # to presses at its old position: it grabs the mouse for its removed axes, and the next
    # button drawn there then fails with "Another Axes already grabs mouse input". So disconnect
    # them now, and drop any grab one of them still holds.
    for button in buttons:
        button.disconnect_events()
    if fig.canvas.mouse_grabber is not None:
        fig.canvas.release_mouse(fig.canvas.mouse_grabber)

    if action[0] == QUIT:
        plt.close(fig)
    else:
        # Clear the figure (rather than closing it) so it stays registered
        # with pyplot and the same window can be reused for the next circuit.
        fig.clf()

    return action[0]


def show_netlist(netlist, title_prefix=None, fig=default_fig):
    """Prepare and interactively display one circuit.

    Labels the netlist's sources, lays it out as a circuit diagram, and shows
    that diagram, then waits for the user to advance to the next circuit or quit.
    If the user clicks "Reassign Gates" instead, the netlist's gates are
    randomly reassigned (see `circuit_generator.assign_gates_randomly`; NOT gates
    are kept) and the modified circuit is displayed, until the user advances or quits.

    Note that reassigning modifies `netlist` in place.

    :param netlist: the netlist (a networkx DiGraph with 'gate' attributes assigned)
                    to lay out and display.
    :param title_prefix: if given, shown before the circuit's Boolean expression
                         in the figure title (e.g. ``"id=12"`` gives ``"id=12: ..."``).
    :param fig: a matplotlib figure to use for the display.
    :returns: True if the user wants to quit, False if they want to advance to the next circuit.
    """
    circuit_layout.assign_source_labels(netlist)

    while True:
        # Recomputed each time through: reassigning the gates changes the expression.
        # The latex format writes negation as \overline{...}, which matplotlib's mathtext
        # renders as a bar over the term when wrapped in $...$.
        expression = f"${circuit_analyzer.circuit_to_expression(netlist, format='latex')}$"
        set_figure_title(f"{title_prefix}: {expression}" if title_prefix else expression, fig=fig)

        circuit_diagram = circuit_layout.layout_circuit(netlist)
        display_circuit(circuit_diagram, fig=fig)

        action = wait_for_user_action(fig=fig, show_reassign_button=True)
        if action != REASSIGN_GATES:
            return action == QUIT
        circuit_generator.assign_gates_randomly(netlist)
